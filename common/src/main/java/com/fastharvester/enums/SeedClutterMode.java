package com.fastharvester.enums;

/**
 * SeedClutterMode: The neat freak's guide to seed management!
 * <p>
 * This enum lets you decide how much seed clutter you can handle. Are you a hoarder, a minimalist, or somewhere in between?
 * </p>
 * <p>
 * Why does this matter? Because too many seeds can drive a farmer mad.
 * </p>
 */
public enum SeedClutterMode {
    /**
     * Keep all the seeds. You never know when you'll need them!
     */
    NORMAL,
    /**
     * Keep fewer seeds. Tidy, but not obsessive.
     */
    REDUCED,
    /**
     * No seed clutter. Marie Kondo would be proud.
     */
    NONE
}
