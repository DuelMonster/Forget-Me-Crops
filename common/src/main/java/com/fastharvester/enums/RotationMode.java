package com.fastharvester.enums;

/**
 * RotationMode: The dance card for your frames!
 * <p>
 * This enum lets you pick how your item frames should spin and twirl. Will they step, spin, or follow the spiral?
 * </p>
 * <p>
 * Why does this matter? Because farming is more fun with a little choreography.
 * </p>
 */
public enum RotationMode {
    /**
     * One step per harvest. Slow and steady wins the race.
     */
    STEP_PER_HARVEST,
    /**
     * Full rotation every harvest. Dizzy yet?
     */
    FULL_ROTATION_PER_HARVEST,
    /**
     * Follow the harvest spiral. The fanciest move of all!
     */
    FOLLOW_HARVEST_SPIRAL
}
